#!/usr/bin/env bash
set -euo pipefail

readonly REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
readonly CACHE_DIR="$REPO_ROOT/.antlr-cache"
readonly GENERATOR_JAR="$CACHE_DIR/antlr4rust-4.13.3-v0.5.0.jar"
readonly GENERATOR_URL="https://github.com/antlr4rust/antlr4/releases/download/v0.5.0/antlr4-4.13.3-SNAPSHOT-complete.jar"
readonly GENERATOR_SHA256="8227a91d45625aec824e31cc7792ecb8b22b973da71f2396e81542b88d897d8f"
readonly COMMITTED_DIR="$REPO_ROOT/src-tauri/src/ledger_parser/generated"
readonly NO_LISTENER_PATCH="$REPO_ROOT/scripts/patch_antlr4rust_no_listener.pl"

usage() {
  echo "usage: $0 [--check]" >&2
}

mode="write"
if [[ ${1:-} == "--check" ]]; then
  mode="check"
  shift
fi
if [[ $# -ne 0 ]]; then
  usage
  exit 2
fi

command -v java >/dev/null || {
  echo "Java 21 or newer is required to regenerate ledger parsers." >&2
  exit 1
}
command -v curl >/dev/null || {
  echo "curl is required to download the pinned antlr4rust generator." >&2
  exit 1
}

java_major="$(java -version 2>&1 | sed -nE '1s/.*version "([0-9]+).*/\1/p')"
if [[ -z "$java_major" || "$java_major" -lt 21 ]]; then
  echo "Java 21 or newer is required; found: $(java -version 2>&1 | head -n 1)" >&2
  exit 1
fi

mkdir -p "$CACHE_DIR"
if [[ ! -f "$GENERATOR_JAR" ]]; then
  curl --fail --location --silent --show-error "$GENERATOR_URL" --output "$GENERATOR_JAR"
fi

actual_sha="$(shasum -a 256 "$GENERATOR_JAR" | awk '{print $1}')"
if [[ "$actual_sha" != "$GENERATOR_SHA256" ]]; then
  echo "antlr4rust generator checksum mismatch" >&2
  echo "expected: $GENERATOR_SHA256" >&2
  echo "actual:   $actual_sha" >&2
  exit 1
fi

tmp_dir="$(mktemp -d "${TMPDIR:-/tmp}/squirrel-antlr.XXXXXX")"
trap 'rm -rf "$tmp_dir"' EXIT

grammar_files=("Ledger.g4")
if [[ -f "$REPO_ROOT/LedgerLexer.g4" ]]; then
  grammar_files=(
    "LedgerLexer.g4"
    "Ledger.g4"
    "Prices.g4"
  )
fi

(
  cd "$REPO_ROOT"
  java -jar "$GENERATOR_JAR" \
    -Dlanguage=Rust \
    -visitor \
    -no-listener \
    -Xexact-output-dir \
    -o "$tmp_dir" \
    "${grammar_files[@]}"
)

# Complete the fork's partial -no-listener implementation without creating
# grammar-specific listener files. See the patcher's comment for details.
for generated_source in "$tmp_dir"/*.rs; do
  perl "$NO_LISTENER_PATCH" "$generated_source"
done

# The .tokens/.interp files are generator diagnostics, not Rust build inputs.
# Keeping only Rust sources also makes drift checks independent of their format.
find "$tmp_dir" -maxdepth 1 -type f ! -name '*.rs' -delete

generated_modules=()
while IFS= read -r generated_module; do
  generated_modules+=("$generated_module")
done < <(find "$tmp_dir" -maxdepth 1 -type f -name '*.rs' -print | sort)

{
  echo "// @generated by scripts/generate_ledger_parsers.sh; do not edit."
  for generated_module in "${generated_modules[@]}"; do
    module_name="$(basename "$generated_module" .rs)"
    echo "pub(crate) mod $module_name;"
  done
} > "$tmp_dir/mod.rs"

if [[ "$mode" == "check" ]]; then
  if [[ ! -d "$COMMITTED_DIR" ]]; then
    echo "Generated parser directory is missing: $COMMITTED_DIR" >&2
    exit 1
  fi
  diff -ru "$COMMITTED_DIR" "$tmp_dir"
  echo "Committed ledger parser sources are up to date."
  exit 0
fi

mkdir -p "$COMMITTED_DIR"
find "$COMMITTED_DIR" -mindepth 1 -maxdepth 1 -type f -delete
cp "$tmp_dir"/*.rs "$COMMITTED_DIR"/
echo "Generated ledger parser sources in $COMMITTED_DIR"
